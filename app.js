const img = document.getElementById('slideImage');
const hotspot = document.getElementById('hotspot');
const stepLabel = document.getElementById('stepLabel');
const slideTitle = document.getElementById('slideTitle');
const counter = document.getElementById('counter');
const stage = document.getElementById('stage');

let slideIndex = 0;
let stepIndex = 0;

function currentSlide() {
  return SLIDES[slideIndex];
}

function clamp(v,min,max) {
  return Math.max(min, Math.min(max, v));
}

function applyStep() {
  const slide = currentSlide();
  const step = slide.steps[stepIndex];
  img.src = slide.file;
  slideTitle.textContent = slide.title;
  counter.textContent = `${slideIndex + 1} / ${SLIDES.length} · etapa ${stepIndex + 1} / ${slide.steps.length}`;

  img.style.transformOrigin = step.origin;
  img.style.transform = `scale(${step.scale})`;

  if (step.box) {
    hotspot.style.display = 'block';
    hotspot.style.left = step.box.x + '%';
    hotspot.style.top = step.box.y + '%';
    hotspot.style.width = step.box.w + '%';
    hotspot.style.height = step.box.h + '%';
  } else {
    hotspot.style.display = 'none';
  }

  stepLabel.textContent = step.label;
  stepLabel.classList.remove('show');
  requestAnimationFrame(() => requestAnimationFrame(() => stepLabel.classList.add('show')));
}

function nextStep() {
  const slide = currentSlide();
  if (stepIndex < slide.steps.length - 1) {
    stepIndex += 1;
    applyStep();
  } else if (slideIndex < SLIDES.length - 1) {
    slideIndex += 1;
    stepIndex = 0;
    applyStep();
  }
}

function prevStep() {
  if (stepIndex > 0) {
    stepIndex -= 1;
    applyStep();
  } else if (slideIndex > 0) {
    slideIndex -= 1;
    stepIndex = currentSlide().steps.length - 1;
    applyStep();
  }
}

document.getElementById('nextBtn').addEventListener('click', nextStep);
document.getElementById('prevBtn').addEventListener('click', prevStep);
document.getElementById('fullBtn').addEventListener('click', () => {
  if (document.fullscreenElement) document.exitFullscreen();
  else document.documentElement.requestFullscreen();
});

document.addEventListener('keydown', (e) => {
  if (['ArrowRight', ' ', 'Enter', 'PageDown'].includes(e.key)) {
    e.preventDefault();
    nextStep();
  }
  if (['ArrowLeft', 'Backspace', 'PageUp'].includes(e.key)) {
    e.preventDefault();
    prevStep();
  }
  if (e.key.toLowerCase() === 'f') {
    if (document.fullscreenElement) document.exitFullscreen();
    else document.documentElement.requestFullscreen();
  }
  if (e.key === 'Home') {
    slideIndex = 0; stepIndex = 0; applyStep();
  }
  if (e.key === 'End') {
    slideIndex = SLIDES.length - 1; stepIndex = currentSlide().steps.length - 1; applyStep();
  }
});

document.getElementById('stage').addEventListener('click', nextStep);

// preload
SLIDES.forEach(s => { const i = new Image(); i.src = s.file; });

applyStep();
